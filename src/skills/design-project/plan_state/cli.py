# Project helpers

def load_docs_tool(root):
    """Import the project's tools/docs.py, or return None when the project has none."""
    path = Path(root) / "tools" / "docs.py"
    if not path.is_file():
        return None
    spec = importlib.util.spec_from_file_location("project_docs_tool", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def require_docs_tool(root):
    tool = load_docs_tool(root)
    if tool is None:
        raise CliError("REFUSED", "tools/docs.py not found; run cinit in the project first, then init again")
    return tool


def next_number(root, prefix, tool):
    return tool.next_number(Path(root) / "docs", prefix)


def docs_tree(root):
    """sha256 of every file under docs/ except plan_state's own files."""
    tree = {}
    docs = Path(root) / "docs"
    if docs.is_dir():
        for p in sorted(docs.rglob("*")):
            if p.is_file() and p.name != ".DS_Store":
                rel = p.relative_to(root).as_posix()
                if not registry.is_state_file(rel):
                    tree[rel] = hashlib.sha256(p.read_bytes()).hexdigest()
    return tree


def read_text(root, rel):
    return (Path(root) / rel).read_text(encoding="utf-8")


def args_hash(obj):
    return hashlib.sha256(store.dumps(obj).encode("utf-8")).hexdigest()


def now():
    return datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0).isoformat()


def find_plan(root, plan):
    if plan:
        return plan
    plans = Path(root) / PLANS_REL
    ids = sorted({p.name.split(".")[0] for p in plans.glob("PLAN-*.journal.jsonl")}, key=registry.number_of) \
        if plans.is_dir() else []
    if not ids:
        raise CliError("REFUSED", "no planning run here; call init <brief> first")
    return ids[-1]


# Index (one row per ID)

INDEX_ORDER = ("F", "M", "G", "R", "US", "BR", "INV", "D", "E", "API", "S", "SEC", "PERF", "QA", "DA", "DEC")


def render_index(state):
    rows = ["| ID | File | Line | Owner | Status | References |", "|---|---|---|---|---|---|"]
    located = {}
    for path, art in sorted(state["artifacts"].items()):
        for id_, b in art["blocks"].items():
            located.setdefault(id_, (path, b))
    for id_, rec in sorted(state["ids"].items(),
                           key=lambda kv: (INDEX_ORDER.index(kv[1]["prefix"]) if kv[1]["prefix"] in INDEX_ORDER
                                           else 99, registry.number_of(kv[0]))):
        path, block = located.get(id_, ("-", None))
        if rec["doc"] in state["artifacts"] and id_ in state["artifacts"][rec["doc"]]["blocks"]:
            path, block = rec["doc"], state["artifacts"][rec["doc"]]["blocks"][id_]
        finding = state["findings"].get(id_)
        status = finding["status"] if finding else (rec.get("decision") or rec["status"])
        owner = finding["owner"] if finding else rec["owner"]
        line = f"{block['start']}-{block['end']}" if block else "-"
        refs = ", ".join(block["refs"]) if block else ""
        origin = f" (origin {rec['origin']})" if rec.get("origin") else ""
        rows.append(f"| {id_}{origin} | {path} | {line} | {owner} | {status} | {refs} |")
    return (f"# {state['plan_id']} index\n\nGenerated by plan_state.py after every successful command. "
            f"Do not edit by hand.\n\n" + "\n".join(rows) + "\n")


# Brief handling

def brief_with_id(text, brief_id, date):
    """Return the brief text with its front matter id set, adding front matter when missing."""
    lines = text.splitlines()
    if lines and lines[0].strip() == "---":
        end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
        if end is not None:
            body = [l for l in lines[1:end] if not l.startswith("id:")]
            return "\n".join(["---", f"id: {brief_id}"] + body + lines[end:]) + "\n"
    title = next((l[2:].strip() for l in lines if l.startswith("# ")), "Brief").replace('"', "'")
    head = ["---", f"id: {brief_id}", f'title: "{title}"', "status: draft", "area: general",
            f"updated: {date}", "---", ""]
    return "\n".join(head + lines) + "\n"


def with_status(text, status):
    """Return the text with its front matter status set."""
    return re.sub(r"(?m)\A(---\n(?:.*\n)*?)status:.*$", lambda m: m.group(1) + f"status: {status}", text, count=1)


# Handoff rendering (8.3)

CRITERION_RE = registry.FLAGS["criterion"]
VERIFY_RE = registry.FLAGS["verification"]


def _block_text(root, path, block):
    lines = read_text(root, path).splitlines()
    return lines[block["start"] - 1: block["end"]]


def _find_block(state, id_):
    for path, art in sorted(state["artifacts"].items()):
        if id_ in art["blocks"]:
            return path, art["blocks"][id_]
    return None, None


def _id_order(i):
    return (registry.prefix_of(i), registry.number_of(i))


# Findings the dev team verifies: a proposed solution or an accepted risk (15.11).
VERIFY_STATUSES = ("fixed", "accepted_risk")


def _one_line(text, limit=160):
    text = " ".join(str(text).split())
    return text if len(text) <= limit else text[:limit - 3].rstrip() + "..."


def verification_items(root, state, touched):
    """
    Map each live slice to its "Doğrulanacak riskler" lines.

    touched maps a slice to the IDs it covers. A finding goes to the first slice that touches
    an ID it names (or the finding itself), else to the first slice. A planned verification line
    of any plan doc that names the finding is its way to verify; CRITICAL is must-verify.
    """
    slices = list(touched)
    out = {s: [] for s in slices}
    if not slices:
        return out
    texts = {path: read_text(root, path).splitlines() for path in sorted(state["artifacts"])
             if (Path(root) / path).is_file()}
    for fid, f in sorted(state["findings"].items(), key=lambda kv: _id_order(kv[0])):
        if f["status"] not in VERIFY_STATUSES:
            continue
        reply = f.get("reply") or ""
        refs = set(registry.ID_RE.findall(" ".join((f["claim"], f["evidence"], reply)))) | {fid}
        if any(registry.prefix_of(r) in ("F", "US", "BR") for r in refs) and \
                all(checks.out_of_scope(state, r) for r in refs if registry.prefix_of(r) in ("F", "US", "BR")):
            continue
        home = next((s for s in slices if refs & touched[s]), slices[0])
        solution = reply[4:] if reply.startswith("FIX ") else "yok, risk kabul edildi"
        verify = next((l.strip().lstrip("-* ").strip() for lines in texts.values() for l in lines
                       if re.search(rf"\b{re.escape(fid)}\b", l) and VERIFY_RE.search(l)), "çözümü bir testle dene, kanıtı Evidence satırına yaz")
        level = f"{f['severity']}, mutlaka doğrula" if f["severity"] == "CRITICAL" else f["severity"]
        out[home].append(f"- {fid} ({level}) | Risk: {_one_line(f['claim'])} | Önerilen çözüm: "
                         f"{_one_line(solution)} | Doğrulama: {_one_line(verify)}")
    return out


def render_tasks(root, state, handoff_id, numbers, date, tool):
    """
    Return one planned task per live slice with its contents.

    Out-of-scope F, US and BR IDs are left out, and so is a slice left with no story. The
    inputs hold the slice's IDs, the feature of each story, and the INV and D IDs one hop
    from the slice's F, US and BR blocks.
    """
    out, touched = [], {}
    blocks = checks._blocks(state)

    def refs_of(i):
        return {r for _, b in blocks.get(i, []) for r in b["refs"]}

    for s in checks.live_slices(state):
        path, block = _find_block(state, s)
        text = _block_text(root, path, block)
        title = re.sub(r"^[#\-*|\s]*" + re.escape(s) + r"[:.\s|]*", "", text[0]).strip(" |") or s
        live = [r for r in block["refs"] if not checks.out_of_scope(state, r)]
        stories = [r for r in live if registry.prefix_of(r) == "US"]
        criteria = []
        for us in stories:
            us_path, us_block = _find_block(state, us)
            if us_block:
                criteria += [f"{l.strip()} ({us})" for l in _block_text(root, us_path, us_block)
                             if CRITERION_RE.search(l)]
        verify = [l.strip().lstrip("-* ").strip() for l in text if VERIFY_RE.search(l)]
        named = {r for r in live if registry.prefix_of(r) in ("F", "US", "BR")}
        named |= {r for us in stories for r in refs_of(us) if registry.prefix_of(r) in ("F", "BR")
                  and not checks.out_of_scope(state, r)}
        hop = {r for i in named for r in refs_of(i) if registry.prefix_of(r) in ("INV", "D")}
        hop |= {i for i in blocks if registry.prefix_of(i) in ("INV", "D") and named & refs_of(i)}
        inputs = sorted(({r for r in live if registry.prefix_of(r) not in ("US", "S")}
                         | {r for r in named if registry.prefix_of(r) != "US"} | hop), key=_id_order)
        contracts = sorted({r for r in inputs if registry.prefix_of(r) in ("E", "API")}
                           | {i for i in blocks if registry.prefix_of(i) in ("E", "API")
                              and (named & refs_of(i))}, key=_id_order)
        touched[s] = {s} | set(live) | named | hop | set(inputs) | set(contracts)
        t_id = f"T-{numbers[s]:04d}"
        full_title = f"{s}: {title}".replace('"', "'")
        body = [
            "---", f"id: {t_id}", f'title: "{full_title}"', "status: draft", "area: general", "owner:",
            f"updated: {date}", "depends_on: []", "related: []", "superseded_by:", "code_paths: []",
            f"handoff: {handoff_id}", f"slice: {s}", "---", "", f"# {full_title}", "",
            "## Goal", title, "", "## Definition of done", *[f"- {c.lstrip('-* ')}" for c in criteria], "",
            "## Doğrulanacak riskler", "", "## Notes", f"- Slice: {s}, stories: {', '.join(stories) or 'none'}.",
            f"- Inputs: plan {state['plan_id']}, ids {', '.join(inputs) or 'none'}.",
            f"- Contracts (entities and endpoints): {', '.join(contracts) or 'none'}.",
            *[f"- Planned verification: {v}" for v in verify], "- Evidence: pending", "",
        ]
        rel = f"{TASKS_REL}/{t_id}-{tool.slugify(full_title)}.md"
        out.append({"slice": s, "path": rel, "t": t_id, "body": body, "stories": stories,
                    "criteria": criteria, "verify": verify})
    items = verification_items(root, state, touched)
    for t in out:
        body = t.pop("body")
        at = body.index("## Doğrulanacak riskler") + 1
        body[at:at] = items[t["slice"]] or ["- yok"]
        t["content"] = "\n".join(body)
    return out


def handoff_precheck(root, state, tasks, tool):
    """
    Docs lint of the staged tasks, taken numbers and the slice rules G3 eligibility uses too.
    """
    errors = list(checks.slice_errors(state))
    tree_ids = {}
    for p in (Path(root) / "docs").rglob("*.md"):
        m = re.search(r"^id:\s*(T-\d+)", p.read_text(encoding="utf-8", errors="replace"), re.M)
        if m:
            tree_ids[m.group(1)] = p.relative_to(root).as_posix()
    for t in tasks:
        try:
            data, _ = tool.parse_front_matter(t["content"])
            missing = [k for k in tool.REQUIRED if not data.get(k)]
            if missing:
                errors.append(f"{t['path']}: missing {', '.join(missing)}")
        except tool.DocsError as e:
            errors.append(f"{t['path']}: {e}")
        other = tree_ids.get(t["t"])
        if other and other != t["path"]:
            errors.append(f"{t['t']} is already used by {other}")
    return errors


